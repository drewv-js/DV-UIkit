/**
 * Event name for step selection.
 * Emitted when a step in the stepper is selected.
 * Payload contains the index (number) of the selected step.
 */
export const STEP_SELECTED_EVENT = 'stepSelected';

/**
 * Event detail type for stepSelect event.
 * Contains the index of the selected step.
 */
export type StepSelectedEventDetail = number;

